# STEP 5.1: turns docs/ring_profile.csv (design height every 10 m) into src/roads/ring/RingProfileData.ts. Run: python3 tools/ring-profile-to-ts.py
import csv
rows = list(csv.DictReader(open('docs/ring_profile.csv')))
st = [float(r['station_m']) for r in rows]
assert all(abs(st[i + 1] - st[i] - 10) < 1e-9 for i in range(len(st) - 1)) and st[0] == 0
ys = [r['design_m'] for r in rows]
with open('src/roads/ring/RingProfileData.ts', 'w', newline='\n') as f:
    f.write('// GENERATED by tools/ring-profile-to-ts.py from docs/ring_profile.csv (Step 3 grade line). Do not edit by hand.\n')
    f.write('/** Finished centreline height (m) of the ring every RING_PROFILE_STEP m of station, from station 0. The ring closes: after the last value comes the first. */\n')
    f.write('export const RING_PROFILE_STEP = 10;\n')
    f.write('export const RING_PROFILE_Y: readonly number[] = [\n')
    for i in range(0, len(ys), 12):
        f.write('  ' + ', '.join(ys[i:i + 12]) + ',\n')
    f.write('];\n')
print(len(ys), 'values')
